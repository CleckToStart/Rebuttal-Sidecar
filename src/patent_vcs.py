"""Transparent Git snapshot manager and expwin Gitea synchronization for patent projects."""

from __future__ import annotations

import base64
import json
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

from proc_utils import run_cmd

PATENT_GITIGNORE = "# Auto-generated by Rebuttal Sidecar\n~$*\n*.tmp\n*.bak\nThumbs.db\n.DS_Store\n"


def _ensure_git_identity(patent_dir: Path) -> None:
    name_res = run_cmd(["git", "config", "user.name"], cwd=patent_dir, timeout=10)
    if name_res.returncode != 0 or not name_res.stdout.strip():
        run_cmd(["git", "config", "user.name", "Patent Author"], cwd=patent_dir, timeout=10)
    email_res = run_cmd(["git", "config", "user.email"], cwd=patent_dir, timeout=10)
    if email_res.returncode != 0 or not email_res.stdout.strip():
        run_cmd(["git", "config", "user.email", "patent@rebuttal-sidecar.local"], cwd=patent_dir, timeout=10)


def ensure_patent_repo(patent_dir: Path) -> bool:
    """Ensure patent_dir is initialized as a local Git repository with safe .gitignore rules."""
    patent_dir.mkdir(parents=True, exist_ok=True)
    gi_path = patent_dir / ".gitignore"
    if not gi_path.is_file():
        gi_path.write_text(PATENT_GITIGNORE, encoding="utf-8")

    if (patent_dir / ".git").exists():
        _ensure_git_identity(patent_dir)
        return True

    res = run_cmd(["git", "init"], cwd=patent_dir, timeout=15)
    if res.returncode != 0:
        return False
    _ensure_git_identity(patent_dir)
    return True


def create_snapshot(patent_dir: Path, message: str, tag: str = "") -> dict:
    """Stage working files and record a transparent Git snapshot (and optional tag)."""
    if not ensure_patent_repo(patent_dir):
        raise RuntimeError("未能初始化本地 Git 版本库，请确认系统已安装 Git。")

    clean_msg = message.strip() or "chore(patent): save version snapshot"
    clean_tag = tag.strip()
    if clean_tag.startswith("-"):
        raise ValueError("Tag 名称不能以 '-' 开头")

    run_cmd(["git", "add", "-A"], cwd=patent_dir, timeout=20)
    st_res = run_cmd(["git", "status", "--porcelain"], cwd=patent_dir, timeout=10)
    head_res = run_cmd(["git", "rev-parse", "--verify", "HEAD"], cwd=patent_dir, timeout=10)
    has_head = head_res.returncode == 0
    created_new = False

    if st_res.stdout.strip() or not has_head:
        commit_cmd = ["git", "commit", "-m", clean_msg]
        if not st_res.stdout.strip() and not has_head:
            commit_cmd.append("--allow-empty")
        c_res = run_cmd(commit_cmd, cwd=patent_dir, timeout=20)
        if c_res.returncode != 0:
            raise RuntimeError(f"保存快照失败: {c_res.stderr.strip() or c_res.stdout.strip()}")
        created_new = True

    if clean_tag:
        t_res = run_cmd(["git", "tag", "-f", clean_tag], cwd=patent_dir, timeout=10)
        if t_res.returncode != 0:
            raise RuntimeError(f"创建版本标签失败: {t_res.stderr.strip()}")

    rev = run_cmd(["git", "rev-parse", "--short", "HEAD"], cwd=patent_dir, timeout=10).stdout.strip()
    return {
        "ref": rev,
        "tag": clean_tag,
        "message": clean_msg,
        "created_new": created_new,
        "snapshots": list_snapshots(patent_dir),
    }


def list_snapshots(patent_dir: Path, limit: int = 50) -> list[dict]:
    """List recorded version snapshots (commits + tags) for a patent directory."""
    if not (patent_dir / ".git").exists():
        return []
    res = run_cmd(
        ["git", "log", f"-n{limit}", "--date=short", "--pretty=format:%h%x00%H%x00%ad%x00%D%x00%s"],
        cwd=patent_dir,
        timeout=15,
    )
    if res.returncode != 0:
        return []

    snapshots: list[dict] = []
    for line in res.stdout.splitlines():
        parts = line.split("\x00", 4)
        if len(parts) != 5:
            continue
        short_h, full_h, date_s, refs_s, subj = parts
        tags = [
            item.strip()[4:].strip()
            for item in refs_s.split(",")
            if item.strip().startswith("tag:")
        ]
        snapshots.append(
            {
                "ref": short_h,
                "commit": full_h,
                "date": date_s,
                "tags": tags,
                "subject": subj,
                "label": f"{short_h} ({date_s}) " + (f"[{', '.join(tags)}] " if tags else "") + subj,
            }
        )
    return snapshots


def read_snapshot_file(patent_dir: Path, rev: str, rel_posix: str) -> bytes:
    """Read raw file bytes at historical Git revision without checking out."""
    clean_rev = rev.strip()
    if not clean_rev or clean_rev.startswith("-"):
        raise ValueError(f"无效的快照引用: {rev}")
    clean_path = rel_posix.strip().replace("\\", "/").lstrip("/")
    res = run_cmd(["git", "show", f"{clean_rev}:{clean_path}"], cwd=patent_dir, timeout=15, text=False)
    if res.returncode != 0:
        err = res.stderr.decode("utf-8", errors="replace") if isinstance(res.stderr, bytes) else res.stderr
        raise FileNotFoundError(f"快照 '{clean_rev}' 中未找到文件 '{clean_path}': {err.strip()}")
    return res.stdout


def _gitea_request(server_url: str, token: str, api_path: str, method: str = "GET", payload: dict | None = None) -> dict:
    base = server_url.strip().rstrip("/")
    if not base.startswith(("http://", "https://")):
        raise ValueError("Gitea 服务器地址需以 http:// 或 https:// 开头")
    url = f"{base}{api_path}"
    data = json.dumps(payload).encode("utf-8") if payload is not None else None
    headers = {"Accept": "application/json", "Content-Type": "application/json"}
    if token.strip():
        headers["Authorization"] = f"token {token.strip()}"
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=12) as resp:
            raw = resp.read().decode("utf-8", errors="replace")
            return json.loads(raw) if raw.strip() else {}
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"Gitea HTTP {exc.code}: {detail[:300]}") from exc
    except OSError as exc:
        raise RuntimeError(f"连接 Gitea 失败: {exc}") from exc


def test_gitea_connection(gitea_cfg: dict) -> dict:
    """Verify expwin/Gitea server reachability and Personal Access Token validity."""
    server_url = str(gitea_cfg.get("server_url", "")).strip()
    token = str(gitea_cfg.get("token", "")).strip()
    info = _gitea_request(server_url, token, "/api/v1/user", method="GET")
    login = str(info.get("login") or info.get("username") or "").strip()
    return {"ok": True, "username": login, "server_url": server_url.rstrip("/")}


def _clean_remote_url(server_url: str, owner: str, repo_name: str) -> str:
    base = server_url.strip().rstrip("/")
    safe_owner = urllib.parse.quote(owner.strip())
    safe_repo = urllib.parse.quote(repo_name.strip())
    return f"{base}/{safe_owner}/{safe_repo}.git"


def _auth_header_arg(gitea_cfg: dict) -> str:
    user = str(gitea_cfg.get("username", "")).strip() or "git"
    token = str(gitea_cfg.get("token", "")).strip()
    encoded = base64.b64encode(f"{user}:{token}".encode("utf-8")).decode("ascii")
    return f"http.extraHeader=Authorization: Basic {encoded}"


def get_remote_url(patent_dir: Path) -> str:
    if not (patent_dir / ".git").exists():
        return ""
    res = run_cmd(["git", "remote", "get-url", "origin"], cwd=patent_dir, timeout=10)
    return res.stdout.strip() if res.returncode == 0 else ""


def create_or_bind_gitea_repo(
    patent_dir: Path,
    repo_name: str,
    description: str,
    gitea_cfg: dict,
) -> dict:
    """Create a private Gitea repository on expwin (or bind if existing) and set clean origin URL."""
    ensure_patent_repo(patent_dir)
    server_url = str(gitea_cfg.get("server_url", "")).strip().rstrip("/")
    token = str(gitea_cfg.get("token", "")).strip()
    org = str(gitea_cfg.get("org", "")).strip()
    clean_name = repo_name.strip()
    if not clean_name:
        raise ValueError("Gitea 仓库名不能为空")

    user_info = test_gitea_connection(gitea_cfg)
    owner = org or str(gitea_cfg.get("username") or user_info["username"])
    api_ep = f"/api/v1/orgs/{urllib.parse.quote(org)}/repos" if org else "/api/v1/user/repos"
    body = {"name": clean_name, "description": description.strip(), "private": True, "auto_init": False}

    clone_url = ""
    try:
        created = _gitea_request(server_url, token, api_ep, method="POST", payload=body)
        clone_url = str(created.get("clone_url") or "")
    except RuntimeError as exc:
        if "409" not in str(exc) and "already exists" not in str(exc).lower():
            raise
    if not clone_url:
        clone_url = _clean_remote_url(server_url, owner, clean_name)

    existing = get_remote_url(patent_dir)
    if existing:
        run_cmd(["git", "remote", "set-url", "origin", clone_url], cwd=patent_dir, timeout=10)
    else:
        run_cmd(["git", "remote", "add", "origin", clone_url], cwd=patent_dir, timeout=10)

    return {"ok": True, "remote_url": clone_url, "owner": owner, "repo_name": clean_name}


def sync_gitea(patent_dir: Path, gitea_cfg: dict, direction: str = "push") -> dict:
    """Push or pull patent snapshots against expwin Gitea using transient auth header."""
    if not (patent_dir / ".git").exists():
        raise RuntimeError("请先初始化或保存至少一次本地快照")
    remote = get_remote_url(patent_dir)
    if not remote:
        raise RuntimeError("当前专利尚未绑定 Gitea 远程仓库，请先点击「一键建仓并绑定」")

    token = str(gitea_cfg.get("token", "")).strip()
    if not token:
        raise RuntimeError("未配置 Gitea Personal Access Token")

    auth_cfg = _auth_header_arg(gitea_cfg)
    if direction == "pull":
        branch_res = run_cmd(["git", "rev-parse", "--abbrev-ref", "HEAD"], cwd=patent_dir, timeout=10)
        branch = branch_res.stdout.strip() or "main"
        res = run_cmd(["git", "-c", auth_cfg, "pull", "--rebase", "origin", branch], cwd=patent_dir, timeout=45)
    else:
        head_res = run_cmd(["git", "rev-parse", "--verify", "HEAD"], cwd=patent_dir, timeout=10)
        if head_res.returncode != 0:
            create_snapshot(patent_dir, "chore(patent): initial snapshot")
        res = run_cmd(["git", "-c", auth_cfg, "push", "-u", "origin", "HEAD", "--tags"], cwd=patent_dir, timeout=45)

    if res.returncode != 0:
        raise RuntimeError(f"Gitea 同步失败: {res.stderr.strip() or res.stdout.strip()}")
    return {"ok": True, "direction": direction, "remote_url": remote, "output": res.stdout.strip() or res.stderr.strip()}
